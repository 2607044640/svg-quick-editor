export function isChineseLocale(): boolean {
	let lang = "en";
	try {
		if (typeof window !== "undefined" && window.localStorage) {
			lang = (window.localStorage.getItem("language") || "en").toLowerCase();
		}
	} catch {
		lang = "en";
	}
	return lang.startsWith("zh");
}

